#!/usr/bin/env python3
"""
Configuration sweeps: play variants of one agent against fixed opponents
and rank the variants. Runs locally or on AWS exactly like tournament.py.

  python eval/sweep.py eval/sweeps/main_time.json                # keys set -> AWS
  python eval/sweep.py eval/sweeps/main_time.json --local --parallel 2
  python eval/sweep.py eval/sweeps/main_time.json --aws --dry    # free check
  python eval/sweep.py eval/sweeps/main_time.json --list         # just show variants

Sweep file (JSON):
  {
    "name": "main_time",            short id, used for folders and team names
    "base": "main",                 agent key (see tournament.py) or path to agent.py
    "opponents": ["full"],          who every variant plays
    "games": 10,                    per variant per opponent; sides alternate
    "mode": "one-at-a-time",        grid | random | one-at-a-time
    "samples": 12,                  random mode: how many variants
    "seed": 1,
    "params": {                     name -> values to try; the FIRST value is the
      "P.D_MAX": [2, 3],            baseline in one-at-a-time mode
      "P.N_MAX": [60, 300]
    }
  }

How a variant is made: the base agent.py is copied to
eval/sweeps/<name>/v00/agent.py, ... with the overrides appended at the end
of the file (e.g. `P.D_MAX = 3` or `SA_ITERS = 1000`). Everything that reads
the constant at run time picks the new value up; default arguments of
functions do not (they are fixed when the function is defined).

Ranking: points per game, then goal difference per game, with the standard
error of the goal difference so you can tell real gains from noise.
"""
import argparse
import itertools
import json
import math
import os
import random
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tournament as T  # noqa: E402

NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)?$")


def variants(cfg):
    params = cfg["params"]
    names = list(params)
    for n in names:
        if not NAME.match(n):
            sys.exit(f"bad parameter name {n!r}: use NAME or Class.NAME")
        if not isinstance(params[n], list) or not params[n]:
            sys.exit(f"{n}: give a non-empty list of values")
    mode = cfg.get("mode", "grid")
    if mode == "grid":
        combos = [dict(zip(names, vals))
                  for vals in itertools.product(*(params[n] for n in names))]
    elif mode == "random":
        rng = random.Random(cfg.get("seed", 1))
        seen, combos = set(), []
        for _ in range(cfg.get("samples", 12) * 20):
            c = {n: rng.choice(params[n]) for n in names}
            key = json.dumps(c, sort_keys=True)
            if key not in seen:
                seen.add(key)
                combos.append(c)
            if len(combos) >= cfg.get("samples", 12):
                break
    elif mode == "one-at-a-time":
        base = {n: params[n][0] for n in names}
        combos = [dict(base)]
        for n in names:
            for v in params[n][1:]:
                c = dict(base)
                c[n] = v
                combos.append(c)
    else:
        sys.exit(f"unknown mode {mode!r}")
    return combos


def build(cfg, combos):
    base = T.spec_of(cfg["base"])
    path, _, cls = base.partition(":")
    if cls and cls != "Agent1":
        sys.exit("sweeps need a base whose class is Agent1")
    src = open(path).read()
    root = os.path.join(HERE, "sweeps", cfg["name"])
    out = []
    for i, c in enumerate(combos):
        vid = f"v{i:02d}"
        d = os.path.join(root, vid)
        os.makedirs(d, exist_ok=True)
        lines = ["", "", "# ---- sweep overrides (generated by eval/sweep.py) ----"]
        lines += [f"{k} = {v!r}" for k, v in c.items()]
        with open(os.path.join(d, "agent.py"), "w") as fh:
            fh.write(src.rstrip("\n") + "\n" + "\n".join(lines) + "\n")
        rel = os.path.relpath(os.path.join(d, "agent.py"), T.ROOT)
        out.append((vid, rel, c))
    return out


def rank(rows, built, opponents):
    by_path = {rel: (vid, c) for vid, rel, c in built}
    stats = {}
    for r in rows:
        if not r.get("valid") or r.get("lg") is None:
            continue
        for side, other in (("l", "r"), ("r", "l")):
            who = r["left"] if side == "l" else r["right"]
            if who not in by_path:
                continue
            gf, ga = r[side + "g"], r[other + "g"]
            s = stats.setdefault(who, {"gd": [], "pts": 0, "W": 0, "D": 0, "L": 0,
                                       "GF": 0, "GA": 0, "cuts": 0, "cpu": 0.0})
            s["gd"].append(gf - ga)
            s["GF"] += gf
            s["GA"] += ga
            s["W" if gf > ga else "D" if gf == ga else "L"] += 1
            s["pts"] += 3 if gf > ga else 1 if gf == ga else 0
            s["cuts"] += r.get(side + "_cuts", 0) or 0
            s["cpu"] = max(s["cpu"], r.get(side + "_cpu_s", 0.0) or 0.0)
    table = []
    for rel, (vid, c) in by_path.items():
        s = stats.get(rel)
        if not s:
            table.append((vid, c, None))
            continue
        n = len(s["gd"])
        mean = sum(s["gd"]) / n
        var = sum((g - mean) ** 2 for g in s["gd"]) / (n - 1) if n > 1 else 0.0
        s.update(n=n, ppg=s["pts"] / n, gdpg=mean, se=math.sqrt(var / n) if n else 0.0)
        table.append((vid, c, s))
    table.sort(key=lambda t: (t[2] is None, -(t[2] or {}).get("ppg", 0),
                              -(t[2] or {}).get("gdpg", 0), t[0]))
    return table


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("sweep")
    ap.add_argument("--list", action="store_true", help="show variants and stop")
    ap.add_argument("--local", action="store_true")
    ap.add_argument("--aws", action="store_true")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--parallel", type=int, default=0)
    ap.add_argument("--half", type=int, default=0)
    ap.add_argument("--shards", type=int, default=T.AWS_SHARDS)
    ap.add_argument("--instance", default=T.AWS_INSTANCE)
    ap.add_argument("--region", default=T.AWS_REGION)
    ap.add_argument("--budget", type=float, default=T.AWS_BUDGET_USD)
    ap.add_argument("--cdeploy-home", default="")
    a = ap.parse_args()

    cfg = json.load(open(a.sweep))
    if not re.match(r"^[A-Za-z0-9_-]{1,20}$", cfg.get("name", "")):
        sys.exit('"name" must be 1-20 letters, digits, - or _')
    combos = variants(cfg)
    games = int(cfg.get("games", 10))
    opps = cfg.get("opponents", ["full"])
    print(f"{len(combos)} variants x {len(opps)} opponent(s) x {games} games "
          f"= {len(combos) * len(opps) * games} matches")
    for i, c in enumerate(combos):
        print(f"  v{i:02d}  " + "  ".join(f"{k}={v!r}" for k, v in c.items()))
    if a.list:
        return
    built = build(cfg, combos)

    fxs = []
    for vid, rel, c in built:
        for o in opps:
            for g in range(games):
                left, right = (rel, o) if g % 2 == 0 else (o, rel)
                fxs.append({"id": len(fxs), "left": left, "right": right, "game": g})
    use_aws = a.aws or (not a.local and T.aws_keys() is not None)
    rows = (T.run_aws(fxs, a) if use_aws
            else T.run_local(fxs, a.parallel, a.dry, None, a.half))

    table = rank(rows, built, opps)
    print()
    print(f"{'var':<5}{'n':>4}{'W':>4}{'D':>4}{'L':>4}{'GF':>5}{'GA':>5}{'ppg':>6}"
          f"{'GD/g':>7}{'+-se':>7}{'cuts':>6}{'CPU':>7}  params")
    for vid, c, s in table:
        ps = "  ".join(f"{k}={v!r}" for k, v in c.items())
        if s is None:
            print(f"{vid:<5}   (no valid games)  {ps}")
            continue
        print(f"{vid:<5}{s['n']:>4}{s['W']:>4}{s['D']:>4}{s['L']:>4}{s['GF']:>5}"
              f"{s['GA']:>5}{s['ppg']:>6.2f}{s['gdpg']:>7.2f}{s['se']:>7.2f}"
              f"{s['cuts']:>6}{s['cpu']:>6.1f}s  {ps}")
    stamp = time.strftime("%Y%m%d-%H%M%S")
    path = os.path.join(T.OUT, f"sweep_{cfg['name']}_{stamp}.json")
    T.save_json(path, {"sweep": cfg, "rows": rows,
                       "ranking": [{"variant": v, "params": c, "stats":
                                    {k: x for k, x in (s or {}).items() if k != "gd"}}
                                   for v, c, s in table]})
    print(f"\nwrote {path}")
    print("A gap smaller than about 2 x se in GD/g is likely noise: confirm the "
          "top variants with more games before adopting them.")


if __name__ == "__main__":
    main()
